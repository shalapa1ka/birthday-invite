#!/usr/bin/env node
/**
 * Guest list generator.
 *
 * Source of truth: guests.local.json (NOT committed — it contains the secret tokens).
 *   { "siteUrl": "https://USER.github.io/REPO/", "guests": [{ "name": "Інна" }, { "name": "Сергій", "token": "…" }] }
 *
 * `npm run guests`:
 *   1. gives every guest without a token a new random 16-char alphanumeric token (saved back to guests.local.json);
 *   2. writes src/config/guests.ts with only SHA-256 hashes of tokens (safe to publish);
 *   3. writes guest-links.local.txt with personal links to send (NOT committed).
 */
import { createHash, randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const sourcePath = `${root}guests.local.json`
const outputPath = `${root}src/config/guests.ts`
const linksPath = `${root}guest-links.local.txt`

if (!existsSync(sourcePath)) {
  writeFileSync(sourcePath, JSON.stringify({ siteUrl: 'https://USERNAME.github.io/REPOSITORY/', guests: [{ name: 'Гість' }] }, null, 2) + '\n')
  console.log(`Created ${sourcePath} — add your guests there and run again.`)
  process.exit(0)
}

const source = JSON.parse(readFileSync(sourcePath, 'utf8'))
if (!Array.isArray(source.guests)) throw new Error('guests.local.json: "guests" must be an array')

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'

/** 16 random letters/digits (~95 bits). Alphanumeric only, so messengers never cut the link. */
function newToken(length = 16) {
  let token = ''
  while (token.length < length) {
    for (const byte of randomBytes(32)) {
      if (byte < 248 && token.length < length) token += ALPHABET[byte % 62] // 248 = 4 * 62, no modulo bias
    }
  }
  return token
}

const seen = new Set()
for (const guest of source.guests) {
  if (typeof guest.name !== 'string' || !guest.name.trim()) throw new Error(`Guest without a name: ${JSON.stringify(guest)}`)
  guest.token ??= newToken()
  if (guest.token.length < 12) throw new Error(`Token for ${guest.name} is too short (min 12 chars)`)
  if (seen.has(guest.token)) throw new Error(`Duplicate token for ${guest.name}`)
  seen.add(guest.token)
}
writeFileSync(sourcePath, JSON.stringify(source, null, 2) + '\n')

const sha256 = (value) => createHash('sha256').update(value).digest('hex')
const entries = source.guests.map((g) => `  { id: '${sha256(g.token)}', name: ${JSON.stringify(g.name)} },`).join('\n')

writeFileSync(
  outputPath,
  `// AUTO-GENERATED by \`npm run guests\` from guests.local.json — do not edit by hand.
// Only SHA-256 hashes of the tokens are stored here, so this file is safe to publish.

export interface Guest {
  /** SHA-256 (hex) of the token from the personal link ?guest=<token>. */
  id: string
  /** Name exactly as it should appear on the invitation. */
  name: string
}

/** One entry = one personal link = one guest (no +1). Also used by the RSVP Worker. */
export const guests: Guest[] = [
${entries}
]
`,
)

const base = source.siteUrl ?? ''
const links = source.guests.map((g) => `${g.name}\t${base}?guest=${g.token}`).join('\n')
writeFileSync(linksPath, links + '\n')

console.log(`✔ ${source.guests.length} guests → src/config/guests.ts (hashes only)`)
console.log(`✔ Personal links → guest-links.local.txt\n`)
console.log(links)
